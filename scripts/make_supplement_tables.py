#!/usr/bin/env python3
"""Build the supplementary solver tables from committed calibration and probe results.

Inputs (copied from the experiment repository; see the ``PROVENANCE.md`` files):
- ``results/calibration/trajectory_checkpoints.csv`` and ``stage_totals.csv``: Gurobi
  time-limit calibration (first window, stage 1 run for 7200 s, earliness stage for 1800 s);
- ``results/solver_probe/*.json`` (HiGHS) and ``results/solver_probe/gurobi/*.json``: first-window
  probes, stage 1 run for 1800 s and earliness stage for 300 s.

Outputs:
- ``manuscript/tables/calibration.tex`` (Table S1);
- ``manuscript/tables/solver_probe.tex`` (Table S2).

Usage
-----
    python scripts/make_supplement_tables.py
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
CHECKPOINTS = [300, 900, 1800, 3600]
AREAS = {"ni": "North Island", "ka": "Kamloops", "pg": "Prince George"}


def _window_label(window: str) -> tuple[str, int, int]:
    ctx, size, sub, _ = window.split("_")
    return AREAS[ctx], int(size), int(sub.removeprefix("sub"))


def _f(x: float, nd: int = 2) -> str:
    return "--" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:,.{nd}f}"


def _na(x: float) -> str:
    """Format a shortfall; ``n/a`` when no node-log line with an incumbent exists before the checkpoint."""
    return "n/a" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:,.2f}"


def calibration_table() -> None:
    cp = pd.read_csv(ROOT / "results" / "calibration" / "trajectory_checkpoints.csv")
    tot = pd.read_csv(ROOT / "results" / "calibration" / "stage_totals.csv")
    sizes = pd.read_csv(ROOT / "results" / "calibration" / "model_sizes.csv").set_index("window")
    lines = [
        "% Generated by scripts/make_supplement_tables.py; do not edit.",
        "\\begin{tabular}{lrrr" + "r" * len(CHECKPOINTS) + "rr" + "rr}",
        "\\toprule",
        " & & & & \\multicolumn{" + str(len(CHECKPOINTS)) + "}{c}{Stage 1: shortfall vs.\\ 7200 s (\\%)}"
        " & \\multicolumn{2}{c}{Stage 1 gap (\\%)} & \\multicolumn{2}{c}{Earliness: shortfall vs.\\ 1800 s (\\%)} \\\\",
        "\\cmidrule(lr){5-" + str(4 + len(CHECKPOINTS)) + "}\\cmidrule(lr){"
        + f"{5 + len(CHECKPOINTS)}-{6 + len(CHECKPOINTS)}" + "}\\cmidrule(lr){"
        + f"{7 + len(CHECKPOINTS)}-{8 + len(CHECKPOINTS)}" + "}",
        "Study area & Blocks & Window (d) & Binaries & " + " & ".join(f"{c} s" for c in CHECKPOINTS)
        + " & 1800 s & 7200 s & 300 s & 900 s \\\\",
        "\\midrule",
    ]
    windows = sorted(cp.window.unique(), key=lambda w: (_window_label(w)[1], _window_label(w)[2], w))
    for w in windows:
        area, size, sub = _window_label(w)
        s1 = cp[(cp.window == w) & (cp.stage == 1)].set_index("checkpoint_s")
        s2 = cp[(cp.window == w) & (cp.stage == 2)].set_index("checkpoint_s")
        t1 = tot[(tot.window == w) & (tot.stage == 1)]
        if not t1.empty and t1.seconds.iloc[0] < CHECKPOINTS[0]:
            cells = [f"optimal ({t1.seconds.iloc[0]:.1f} s)"] + [""] * (len(CHECKPOINTS) - 1)
            gaps = ["0.00", "0.00"]
        else:
            cells = [_na(s1.shortfall_vs_final_pct.get(c, math.nan)) for c in CHECKPOINTS]
            gaps = [_f(s1.gap_pct.get(1800, math.nan)), _f(s1.gap_pct.get(7200, math.nan))]
        early = [_na(s2.shortfall_vs_final_pct.get(c, math.nan)) for c in (300, 900)]
        nbin = f"{int(sizes.binaries.get(w)):,}" if w in sizes.index else "--"
        lines.append(f"{area} & {size} & {sub} & {nbin} & " + " & ".join(cells + gaps + early) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    (ROOT / "manuscript" / "tables" / "calibration.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def probe_table() -> None:
    rows = []
    for backend, folder in [("HiGHS", ROOT / "results" / "solver_probe"), ("Gurobi", ROOT / "results" / "solver_probe" / "gurobi")]:
        for f in sorted(folder.glob("*.json")):
            d = json.loads(f.read_text(encoding="utf-8"))
            it = d["summary"]["iterations"][0]
            rows.append(
                {
                    "backend": backend,
                    "window": f.stem,
                    "planned": it.get("planned_delivered") or 0.0,
                    "locked": it.get("locked_delivered") or 0.0,
                    "objective": it.get("objective"),
                }
            )
    df = pd.DataFrame(rows)
    lines = [
        "% Generated by scripts/make_supplement_tables.py; do not edit.",
        "\\begin{tabular}{lrrrrrr}",
        "\\toprule",
        " & & & \\multicolumn{2}{c}{HiGHS (m$^3$)} & \\multicolumn{2}{c}{Gurobi (m$^3$)} \\\\",
        "\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}",
        "Study area & Blocks & Window (d) & Planned & Locked & Planned & Locked \\\\",
        "\\midrule",
    ]
    windows = sorted(df.window.unique(), key=lambda w: (_window_label(w)[1], _window_label(w)[2], w))
    for w in windows:
        area, size, sub = _window_label(w)
        h = df[(df.window == w) & (df.backend == "HiGHS")]
        g = df[(df.window == w) & (df.backend == "Gurobi")]
        cell = lambda d, c: _f(d[c].iloc[0], 0) if not d.empty else "--"  # noqa: E731
        lines.append(
            f"{area} & {size} & {sub} & {cell(h, 'planned')} & {cell(h, 'locked')} & {cell(g, 'planned')} & {cell(g, 'locked')} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}"]
    (ROOT / "manuscript" / "tables" / "solver_probe.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    calibration_table()
    probe_table()
    print((ROOT / "manuscript" / "tables" / "calibration.tex").read_text())
    print((ROOT / "manuscript" / "tables" / "solver_probe.tex").read_text())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
