#!/usr/bin/env python3
"""Build Table 1 (scenario characteristics) from the FHOPS scenario bundles.

Reads ``data/input/scenarios/<area>_<size>/`` in the experiment repository
(``UBC-FRESH/jaffray-masc-fhops-model``) and writes

- ``results/scenarios.csv``: one row per scenario (source of every number in Table 1);
- ``manuscript/tables/scenarios.tex``: the LaTeX tabular included by the manuscript.

Usage
-----
    python scripts/make_table_scenarios.py --model-repo ../jaffray-masc-fhops-model
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
AREAS = {"ni": "North Island", "ka": "Kamloops", "pg": "Prince George"}
SIZES = ["6", "18", "40"]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--model-repo", type=Path, default=ROOT.parent / "jaffray-masc-fhops-model")
    args = parser.parse_args()

    rows = []
    for area, area_name in AREAS.items():
        for size in SIZES:
            base = args.model_repo / "data" / "input" / "scenarios" / f"{area}_{size}"
            blocks = pd.read_csv(base / "data" / "blocks.csv")
            machines = pd.read_csv(base / "data" / "machines.csv")
            landings = pd.read_csv(base / "data" / "landings.csv")
            scenario = yaml.safe_load((base / "scenario.yaml").read_text(encoding="utf-8"))
            rows.append(
                {
                    "scenario": f"{area}_{size}",
                    "area": area_name,
                    "blocks": len(blocks),
                    "machines": len(machines),
                    "machines_per_role": "/".join(
                        str(int((machines["role"] == r).sum()))
                        for r in ["feller_buncher", "grapple_skidder", "processor", "loader"]
                    ),
                    "landings": len(landings),
                    "landing_daily_capacity": int(landings["daily_capacity"].iloc[0]),
                    "num_days": int(scenario["num_days"]),
                    "total_volume_m3": blocks["work_required"].sum(),
                    "mean_block_volume_m3": blocks["work_required"].mean(),
                    "mean_slope_pct": blocks["ground_slope_percent"].mean(),
                    "mean_stem_size_m3": blocks["avg_stem_size_m3"].mean(),
                }
            )
    df = pd.DataFrame(rows)
    (ROOT / "results").mkdir(exist_ok=True)
    df.to_csv(ROOT / "results" / "scenarios.csv", index=False)

    lines = []
    for _, r in df.iterrows():
        lines.append(
            f"{r.area} & {r.blocks} & {r.machines} ({r.machines_per_role}) & "
            f"{r.total_volume_m3:,.0f} & {r.mean_block_volume_m3:,.0f} & {r.mean_slope_pct:.1f} & "
            f"{r.mean_stem_size_m3:.2f} \\\\"
        )
    out = ROOT / "manuscript" / "tables" / "scenarios.tex"
    out.parent.mkdir(parents=True, exist_ok=True)
    header = [
        "% Generated by scripts/make_table_scenarios.py; do not edit.",
        "\\begin{tabular}{lrlrrrr}",
        "\\toprule",
        "Study area & Blocks & Machines & Volume (m$^3$) & Mean block (m$^3$) & Slope (\\%) & Stem (m$^3$) \\\\",
        "\\midrule",
    ]
    footer = ["\\bottomrule", "\\end{tabular}"]
    out.write_text("\n".join(header + lines + footer) + "\n", encoding="utf-8")
    print(df.round(2).to_string(index=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
